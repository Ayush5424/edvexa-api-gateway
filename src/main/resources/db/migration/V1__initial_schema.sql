CREATE TABLE services (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(128) NOT NULL UNIQUE,
    base_url VARCHAR(512) NOT NULL,
    path_prefix VARCHAR(128) NOT NULL UNIQUE,
    connection_timeout_ms INT NOT NULL DEFAULT 5000,
    response_timeout_ms INT NOT NULL DEFAULT 10000,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(256) NOT NULL,
    role VARCHAR(32) NOT NULL DEFAULT 'ROLE_ADMIN',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE api_keys (
    id VARCHAR(64) PRIMARY KEY,
    client_name VARCHAR(128) NOT NULL,
    key_hash VARCHAR(128) NOT NULL UNIQUE,
    key_prefix VARCHAR(16) NOT NULL,
    rate_limit_per_minute INT NOT NULL DEFAULT 60,
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE idempotency_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id VARCHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    response_code INT,
    response_headers TEXT,
    response_body TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_client_idempotency UNIQUE (client_id, idempotency_key)
);

CREATE TABLE gateway_request_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correlation_id VARCHAR(64) NOT NULL,
    client_id VARCHAR(64),
    service_id VARCHAR(64),
    http_method VARCHAR(16) NOT NULL,
    request_path VARCHAR(512) NOT NULL,
    status_code INT NOT NULL,
    latency_ms BIGINT NOT NULL,
    retry_count INT NOT NULL DEFAULT 0,
    circuit_breaker_state VARCHAR(32),
    outcome_category VARCHAR(32) NOT NULL,
    error_message VARCHAR(512),
    timestamp TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_services_path_prefix ON services(path_prefix);
CREATE INDEX idx_services_enabled ON services(enabled);
CREATE INDEX idx_api_keys_key_hash ON api_keys(key_hash);
CREATE INDEX idx_api_keys_status ON api_keys(status);
CREATE INDEX idx_idempotency_expires_at ON idempotency_records(expires_at);
CREATE INDEX idx_request_logs_timestamp ON gateway_request_logs(timestamp);
CREATE INDEX idx_request_logs_correlation_id ON gateway_request_logs(correlation_id);
CREATE INDEX idx_request_logs_service_id ON gateway_request_logs(service_id);
CREATE INDEX idx_request_logs_client_id ON gateway_request_logs(client_id);
CREATE INDEX idx_request_logs_outcome ON gateway_request_logs(outcome_category);
